import sanitizeHtml from "sanitize-html";
export function sanitizeDocument(html: string) {
  return sanitizeHtml(html, {
    allowedTags: [
      "p",
      "div",
      "span",
      "br",
      "strong",
      "b",
      "em",
      "i",
      "u",
      "s",
      "strike",
      "h1",
      "h2",
      "h3",
      "h4",
      "h5",
      "h6",
      "ul",
      "ol",
      "li",
      "blockquote",
      "pre",
      "code",
      "hr",
      "a",
      "table",
      "thead",
      "tbody",
      "tfoot",
      "tr",
      "th",
      "td",
      "colgroup",
      "col",
      "img",
      "sub",
      "sup",
      "mark",
    ],
    allowedAttributes: {
      "*": ["style"],
      a: ["href", "title", "target", "rel"],
      td: ["colspan", "rowspan", "colwidth"],
      th: ["colspan", "rowspan", "colwidth"],
      table: ["width"],
      col: ["width"],
      ol: ["start"],
      mark: ["data-color"],
      img: ["src", "alt", "title", "width", "height"],
    },
    allowedSchemes: ["http", "https", "mailto"],
    allowedSchemesByTag: { img: ["data"] },
    allowProtocolRelative: false,
    allowedStyles: {
      "*": {
        "text-align": [/^(left|right|center|justify)$/],
        "font-family": [/^[a-zA-Z0-9 ,'"-]+$/],
        "font-size": [/^(?:[8-9]|[1-6]\d|7[0-2])(?:px|pt)$/],
        "font-weight": [/^(?:normal|bold|[1-9]00)$/],
        "font-style": [/^(normal|italic)$/],
        "text-decoration": [/^(underline|line-through|none)$/],
        color: [/^#[0-9a-fA-F]{3,8}$/, /^rgb\(\s*\d+,\s*\d+,\s*\d+\s*\)$/],
        "background-color": [
          /^#[0-9a-fA-F]{3,8}$/,
          /^rgb\(\s*\d+,\s*\d+,\s*\d+\s*\)$/,
        ],
        "line-height": [/^[12](?:\.\d+)?$/],
        width: [/^\d+(?:px|pt|%)$/],
        height: [/^\d+(?:px|pt)$/],
        border: [/^\d+px (?:solid|dashed) #[0-9a-fA-F]{3,8}$/],
        "border-collapse": [/^collapse$/],
        padding: [/^[0-9.]+(?:px|pt)$/],
      },
    },
    exclusiveFilter: (frame) =>
      frame.tag === "img" &&
      !/^data:image\/(?:png|jpeg|webp);base64,[a-zA-Z0-9+/=\r\n]+$/.test(
        frame.attribs.src || "",
      ),
    transformTags: {
      a: (_tag, attrs) => ({
        tagName: "a",
        attribs: { ...attrs, rel: "noopener noreferrer" },
      }),
    },
  });
}
